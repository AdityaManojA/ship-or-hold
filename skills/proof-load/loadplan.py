#!/usr/bin/env python3
"""Plan a load test and score the result against a budget. Standard library only.

This tool generates nothing on the network itself. It writes a load plan (a runner
script template and a budget), and it turns a finished run's numbers into a
pass/fail against that budget in the ledger. The load is generated by a real tool
(k6 when installed) or by a driver you run; the numbers come back here to be judged.

    python3 loadplan.py plan --target http://localhost:3000/ --vus 50 --duration 60 --out proof/load
    python3 loadplan.py record --measured measured.json --budget proof/load/budget.json
    python3 loadplan.py from-k6 --summary k6-summary.json --budget proof/load/budget.json
    python3 loadplan.py status
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "proof-core"))
import ledger  # noqa: E402
import num  # noqa: E402

SKILL = "proof-load"

DEFAULT_BUDGET = [
    {"id": "p95_ms", "unit": "ms", "budget": 500, "op": "<=", "label": "95th percentile latency"},
    {"id": "p99_ms", "unit": "ms", "budget": 1000, "op": "<=", "label": "99th percentile latency"},
    {"id": "error_rate", "unit": "fraction", "budget": 0.01, "op": "<=", "label": "share of failed requests"},
    {"id": "rps", "unit": "req/s", "budget": 50, "op": ">=", "label": "requests served per second"},
]

_K6_TEMPLATE = """\
// Load plan for %(target)s. Run with: k6 run this-file.js
// Needs k6 installed (k6.io). This script is generated; adjust as needed.
import http from 'k6/http';
import { check, sleep } from 'k6';

export const options = {
  vus: %(vus)d,
  duration: '%(duration)ds',
  thresholds: {
    http_req_duration: ['p(95)<%(p95)d', 'p(99)<%(p99)d'],
    http_req_failed: ['rate<%(err)s'],
  },
};

export default function () {
  const res = http.get(%(target)r);
  check(res, { 'status is 2xx': (r) => r.status >= 200 && r.status < 300 });
  sleep(1);
}

// After the run, export a summary with:  k6 run --summary-export k6-summary.json this-file.js
// then:  loadplan.py from-k6 --summary k6-summary.json --budget budget.json
"""


def cmd_plan(a):
    why = ledger.authorised_for(a.dir, a.target)
    if why:
        raise SystemExit("Not writing a load plan: %s. Load against a host you do not own can take it "
                         "down; point it at a local or staging copy, or record the target with /proof-plan." % why)
    out = a.out or os.path.join("proof", "load")
    os.makedirs(out, exist_ok=True)
    budget = [dict(m) for m in DEFAULT_BUDGET]
    # fold the requested p95/p99 into the budget if the user overrode them
    for m in budget:
        if m["id"] == "p95_ms" and a.p95:
            m["budget"] = a.p95
        if m["id"] == "p99_ms" and a.p99:
            m["budget"] = a.p99
        if m["id"] == "rps" and a.rps:
            m["budget"] = a.rps
    ledger.guard_out(os.path.join(out, "budget.json"), a.dir, a.force, ours='"p95_ms"')
    ledger.guard_out(os.path.join(out, "load.js"), a.dir, a.force, ours="// Load plan for ")
    with open(os.path.join(out, "budget.json"), "w", encoding="utf-8") as fh:
        json.dump({"metrics": budget}, fh, indent=2)
    p95 = next(m["budget"] for m in budget if m["id"] == "p95_ms")
    p99 = next(m["budget"] for m in budget if m["id"] == "p99_ms")
    err = next(m["budget"] for m in budget if m["id"] == "error_rate")
    script = _K6_TEMPLATE % {"target": a.target, "vus": a.vus, "duration": a.duration,
                             "p95": int(p95), "p99": int(p99), "err": err}
    with open(os.path.join(out, "load.js"), "w", encoding="utf-8") as fh:
        fh.write(script)
    print("%s wrote a load plan to %s: budget.json and load.js (%d VUs for %ds against %s)"
          % (ledger.OK, out, a.vus, a.duration, a.target))
    print("Only run load against a target you own or are authorised to test. Then record the result.")
    return 0


def _load_budget(path):
    with open(path, encoding="utf-8") as fh:
        return json.load(fh)["metrics"]


def _score(dir_, measured, budget, source):
    metrics = []
    missing = []
    for b in budget:
        if b["id"] not in measured:
            missing.append(b["id"])
            continue
        value = num.parse_number(measured[b["id"]], field=b["id"])
        metrics.append({"id": b["id"], "value": value, "unit": b["unit"],
                        "budget": num.parse_number(b["budget"], field=b["id"] + ".budget"),
                        "op": b["op"], "source": source})
    if missing:
        raise SystemExit("measured result is missing: %s (a missing number is not a pass)" % ", ".join(missing))
    ledger.write_scores(dir_, SKILL, metrics)
    ledger.init_coverage(dir_, SKILL, [("load", "Load test against the budget")])
    ledger.mark_coverage(dir_, SKILL, "load", "covered", note=source)
    return metrics


def cmd_record(a):
    with open(a.measured, encoding="utf-8") as fh:
        measured = json.load(fh)
    metrics = _score(a.dir, measured, _load_budget(a.budget), a.source or "measured.json")
    _print_scores(metrics)
    return 0


def cmd_from_k6(a):
    with open(a.summary, encoding="utf-8") as fh:
        data = json.load(fh)
    m = data.get("metrics", {})
    try:
        dur = m["http_req_duration"]["values"]
        failed = m["http_req_failed"]["values"]
        reqs = m.get("http_reqs", {}).get("values", {})
    except (KeyError, TypeError):
        raise SystemExit("this does not look like a k6 summary (no http_req_duration). Check the file.")
    measured = {
        "p95_ms": dur.get("p(95)"),
        "p99_ms": dur.get("p(99)"),
        "error_rate": failed.get("rate", failed.get("value")),
        "rps": reqs.get("rate"),
    }
    measured = {k: v for k, v in measured.items() if v is not None}
    metrics = _score(a.dir, measured, _load_budget(a.budget), "k6 summary")
    _print_scores(metrics)
    return 0


def _print_scores(metrics):
    print("Load result against budget:")
    for m in metrics:
        ok = ledger.metric_passes(m)
        print("  %s %s = %s %s (budget %s %s) " % (ledger.OK if ok else ledger.BAD, m["id"],
                                                   _fmt(m["value"]), m["unit"], m["op"], _fmt(m["budget"])))
    failed = [m for m in metrics if not ledger.metric_passes(m)]
    print(("%s %d metric(s) over budget." % (ledger.BAD, len(failed))) if failed
          else "%s every metric within budget." % ledger.OK)


def _fmt(x):
    return ("%d" % x) if float(x).is_integer() else ("%.3f" % x)


def cmd_status(a):
    scores = [s for s in ledger.load_all_scores(a.dir) if s["skill"] == SKILL]
    if not scores:
        print("no load result recorded yet.")
        return 0
    _print_scores(scores[0]["metrics"])
    return 0


def main(argv=None):
    ledger.console()
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--dir", default="proof")
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("plan", help="write a load plan and budget")
    p.add_argument("--target", required=True)
    p.add_argument("--vus", type=int, default=50)
    p.add_argument("--duration", type=int, default=60)
    p.add_argument("--p95", type=int)
    p.add_argument("--p99", type=int)
    p.add_argument("--rps", type=int)
    p.add_argument("--out")
    p.add_argument("--force", action="store_true", help="overwrite the file even if it is not one Proof wrote")
    p.set_defaults(func=cmd_plan)
    r = sub.add_parser("record", help="score a measured result against the budget")
    r.add_argument("--measured", required=True)
    r.add_argument("--budget", required=True)
    r.add_argument("--source")
    r.set_defaults(func=cmd_record)
    k = sub.add_parser("from-k6", help="score a k6 summary export against the budget")
    k.add_argument("--summary", required=True)
    k.add_argument("--budget", required=True)
    k.set_defaults(func=cmd_from_k6)
    sub.add_parser("status", help="recorded load result").set_defaults(func=cmd_status)
    a = ap.parse_args(argv)
    return a.func(a)


if __name__ == "__main__":
    sys.exit(main())
